/**
 * Returns the capability manifest for a given widget type.
 */
export function getWidgetCapability(type: string): WidgetCapability | undefined {
  return WIDGET_CAPABILITIES[type];
}

/**
 * Returns true if the widget type is officially supported in static export.
 */
export function isStaticCompatible(type: string): boolean {
  const cap = WIDGET_CAPABILITIES[type];
  return Boolean(cap && cap.staticExport);
}
